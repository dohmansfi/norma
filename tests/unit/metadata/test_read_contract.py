CANONICAL = {
    "title": "Perché 東京 🎵", "artist": "Test Artist", "album_artist": "Norma fixtures", "album": "Demo set",
    "date": "2026-10-05", "track": 3, "track_total": 12, "disc": 1, "disc_total": 2, "genre": "Demo",
    "composer": "Composer", "comment": 'Line one\nLine two; comma, quote "', "compilation": True,
}
VARIANTS = {"wav24": "wav", "aiff24": "aiff", "flac24": "flac", "alac24": "mp4", "mp3-v0": "mp3", "aac256": "mp4"}


def _walk(value, seen=None):
    """Every object reachable from a C-06 record, for the no-library-object invariant."""
    seen = set() if seen is None else seen
    if id(value) in seen:
        return
    seen.add(id(value))
    yield value
    if dataclasses.is_dataclass(value):
        for item in dataclasses.fields(value):
            yield from _walk(getattr(value, item.name), seen)
    elif isinstance(value, Mapping):
        for key, item in value.items():
            yield from _walk(key, seen)
            yield from _walk(item, seen)
    elif isinstance(value, (tuple, list, set, frozenset)):
        for item in value:
            yield from _walk(item, seen)


def assert_contract(tags: SourceTags) -> None:
    for obj in _walk(tags):
        assert not type(obj).__module__.startswith("mutagen"), type(obj)
        assert not isinstance(obj, (list, dict, bytearray, set)), type(obj)
    identities = [item.identity for item in tags.native_inventory]
    assert len(identities) == len(set(identities))
    assert sorted(identities) == sorted(i for ids in tags.stores.values() for i in ids)
    for store, ids in tags.stores.items():
        assert all(identity.startswith(f"store:{store}:") for identity in ids)
    for item in tags.native_inventory:
        assert isinstance(item, RawNativeItem) and isinstance(item.payload, bytes)
        assert item.payload_encoding in (reader.RAW, reader.JSON)
        assert (item.native_version is not None) == (item.store == "id3v2")
    for item in tags.non_tag_items:
        assert isinstance(item, NonTagItem)
        if item.payload is not None:
            assert hashlib.sha256(item.payload).hexdigest() == item.payload_sha256
    for tag in tags.fields.values():
        assert isinstance(tag, TagValue) and not isinstance(tag.value, Artwork)
        assert all(part in identities for part in tag.locator.split(","))
    for tag in tags.artwork:
        assert isinstance(tag.value, Artwork) and tag.locator in identities
    with pytest.raises(dataclasses.FrozenInstanceError):
        tags.fields = {}  # type: ignore[misc]


