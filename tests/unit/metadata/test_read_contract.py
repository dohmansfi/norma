@pytest.mark.parametrize("variant", list(VARIANTS))
def test_f13_canonical_object_in_every_target(variant: str, fixture_path, build) -> None:
    path = fixture_path("F-13", variant)
    before = (hashlib.sha256(path.read_bytes()).hexdigest(), os.stat(path).st_mtime_ns)
    tags = read_source_tags(path, VARIANTS[variant])
    assert (hashlib.sha256(path.read_bytes()).hexdigest(), os.stat(path).st_mtime_ns) == before
    assert_contract(tags)
    assert {name: tag.value for name, tag in tags.fields.items()} == CANONICAL
    assert {name: tag.value for name, tag in tags.extras.items()} == {"DEMO_NOTE": "seedless"}
    assert [(tag.value.data, tag.value.picture_type, tag.value.mime) for tag in tags.artwork] == \
        [(build.fixtures.cover_png(), 3, "image/png")]
    assert tags.internal_conflicts == ()
    assert read_processing_mark(tags).validity == "absent"
    primary = {"wav": "id3v2", "aiff": "id3v2", "mp3": "id3v2", "flac": "vorbis", "mp4": "mp4"}[VARIANTS[variant]]
    assert {tag.system for tag in tags.fields.values()} == {primary}
    if primary == "id3v2":
        assert {item.native_version for item in tags.native_inventory if item.store == "id3v2"} == {"2.3"}
        assert set(tags.fields["date"].locator.split(",")) == {"store:id3v2:TYER", "store:id3v2:TDAT"}


def test_f13_conflicting_wav(fixture_path) -> None:
    tags = read_source_tags(fixture_path("F-13", "conflict"), "wav")
    assert_contract(tags)
    raw = {item.identity: item.payload for item in tags.native_inventory}
    assert raw["store:riff-info:INAM"].rstrip(b"\x00") == b"INFO title"
    assert tags.fields["title"].value == CANONICAL["title"] and tags.fields["title"].system == "id3v2"
    assert [(c.key, c.old_value, c.new_value) for c in tags.internal_conflicts] == \
        [("field:title", "INFO title", CANONICAL["title"])]


def test_f18_chunks_are_inventoried_with_exact_payloads(fixture_path) -> None:
    import struct
    tags = read_source_tags(fixture_path("F-18", "chunks"), "wav")
    assert_contract(tags)
    items = {item.identity: item for item in tags.non_tag_items}
    assert list(items) == ["item:chunk:cue ", "item:chunk:bext", "item:chunk:iXML"]
    assert items["item:chunk:cue "].payload == struct.pack("<III4sIII", 1, 1, 48000, b"data", 0, 0, 48000)
    assert len(items["item:chunk:bext"].payload) == 602
    assert items["item:chunk:bext"].payload.startswith(b"Norma fixture\x00")
    assert items["item:chunk:iXML"].payload == b"<BWFXML><PROJECT>Norma fixture</PROJECT></BWFXML>"


@pytest.mark.parametrize(("variant", "validity"), [("mark-valid", "valid"), ("mark-invalid", "malformed")])
def test_f18_marks(variant: str, validity: str, fixture_path) -> None:
    tags = read_source_tags(fixture_path("F-18", variant), "flac")
    mark = read_processing_mark(tags)
    assert (mark.validity, mark.locator) == (validity, "store:vorbis:NORMA")
    if validity == "valid":
        assert (mark.target_lufs, mark.mode, mark.origin_codec) == (-16.0, "limit", "pcm_s24le")
    assert "NORMA" not in tags.extras


