def test_container_without_md3_row_is_refused(audio) -> None:
    with pytest.raises(ValueError, match="no MD3 store row"):
        read_source_tags(audio("wav"), "caf")


def test_vanished_source_is_source_changed(tmp_path: Path) -> None:
    with pytest.raises(FileFailure) as error:
        read_source_tags(tmp_path / "missing.wav", "wav")
    assert (error.value.reason, error.value.stage) == ("source_changed", "tags_read")


def test_unreadable_source_is_permission_denied(audio) -> None:
    path = audio("wav")
    path.chmod(0)
    try:
        if os.access(path, os.R_OK):
            pytest.skip("running with privileges that ignore file modes")
        with pytest.raises(FileFailure) as error:
            read_source_tags(path, "wav")
        assert error.value.reason == "permission_denied"
    finally:
        path.chmod(0o644)


@pytest.mark.parametrize("kind", ["wav", "aiff", "flac", "mp3", "alac"])
def test_truncated_files_do_not_raise(kind: str, audio, build) -> None:
    path = audio(kind)
    data = path.read_bytes()
    path.write_bytes(data[: max(12, len(data) // 3)])
    assert_contract(read_source_tags(path, build.container(kind)))


def test_read_module_imports_only_mutagen_and_its_layer() -> None:
    tree = ast.parse(Path(reader.__file__).read_text(encoding="utf-8"))
    roots = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            roots.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            roots.add(node.module)
    third_party = {name.split(".")[0] for name in roots} - set(sys.stdlib_module_names) - {"norma", "__future__"}
    assert third_party == {"mutagen"}
    assert {name for name in roots if name.startswith("norma")} == {"norma.errors", "norma.metadata", "norma.models"}
    assert "subprocess" not in roots


def test_metadata_package_initialiser_is_inert() -> None:
    result = subprocess.run(
        [sys.executable, "-c", "import sys, norma.metadata; "
         "print(sorted(n for n in sys.modules if n.startswith(('mutagen', 'norma.metadata.'))))"],
        capture_output=True, text=True, timeout=60, check=False)
    assert result.returncode == 0, result.stderr
    assert result.stdout.strip() == "[]"
